   A lancer DEUX fois avec sqlplus, sortie conservee :
     - avant le deploiement (reference)  : sqlplus -S CMS_RFC@cmsprod @control_load.sql > avant.txt
     - apres le chargement suivant        : sqlplus -S CMS_RFC@cmsprod @control_load.sql > apres.txt
   Aucune ecriture. Perimetre : les 4 statuts actifs d'Extractor.
   Les effectifs du 13/11 sont des references, pas des valeurs attendues
