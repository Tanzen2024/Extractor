SET LINESIZE 200 PAGESIZE 500 FEEDBACK OFF TIMING ON
COLUMN SEGMENTATION FORMAT A26
COLUMN UNIVERS FORMAT A24

PROMPT == 0. Chargement : date, volume, structure
SELECT MAX(UPDATED_AT) AS UPDATED_AT, COUNT(*) AS LIGNES FROM CMS_RFC.TB_CUSTOMERS_LIST;
SELECT COUNT(*) AS NB_COLONNES FROM ALL_TAB_COLUMNS WHERE OWNER = 'CMS_RFC' AND TABLE_NAME = 'TB_CUSTOMERS_LIST';
SELECT TO_CHAR(TRUNC(MAX(LASTPURCHASE_DATE)), 'YYYY-MM-DD') AS REF_DATE,
       TO_CHAR(MAX(VC_DATE), 'YYYY-MM-DD') AS DERNIER_VC_DATE
FROM CMS_RFC.PREPAID_PROFILE_P;

PROMPT == 1. PREPAID actifs par segment (+ total)
PROMPT    Reference 13/11 apres deploiement (simulation) : 1-Stable 254096 / 2-InStable 234747 /
PROMPT    3-At Risk 212146 / 4-Suspect Dormant 86075 / 5-Dormant 315317 / 6-Never Vending 11016 / total 1113397
SELECT NVL(SEGMENTATION, '(NON CLASSE)') AS SEGMENTATION, COUNT(*) AS CLIENTS
FROM CMS_RFC.TB_CUSTOMERS_LIST
WHERE METER = 'PREPAID'
  AND TRIM(STATUS) IN ('ACTIVE', 'ACTIVE (PENDING BILLING)', 'SUSPENDED (DELINQUENT ACCOUNT)', 'INACTIVATION IN PROCESS.')
GROUP BY ROLLUP (NVL(SEGMENTATION, '(NON CLASSE)'))
ORDER BY 1;

PROMPT == 2. PREPAID hors nomenclature (apres deploiement : aucune ligne attendue)
SELECT NVL(SEGMENTATION, '(NON CLASSE)') AS SEGMENTATION, COUNT(*) AS CLIENTS
FROM CMS_RFC.TB_CUSTOMERS_LIST
WHERE METER = 'PREPAID'
  AND TRIM(STATUS) IN ('ACTIVE', 'ACTIVE (PENDING BILLING)', 'SUSPENDED (DELINQUENT ACCOUNT)', 'INACTIVATION IN PROCESS.')
  AND (SEGMENTATION IS NULL OR SEGMENTATION NOT IN
       ('1-Stable', '2-InStable', '3-At Risk', '4-Suspect Dormant', '5-Dormant', '6-Never Vending'))
GROUP BY SEGMENTATION;

PROMPT == 3. Doublons par contrat (aucune ligne attendue)
SELECT CONTRACT, COUNT(*) AS LIGNES
FROM CMS_RFC.TB_CUSTOMERS_LIST
GROUP BY CONTRACT
HAVING COUNT(*) > 1
FETCH FIRST 20 ROWS ONLY;

PROMPT == 4. Recence 30-59 jours (comptage independant) x segment affecte
PROMPT    Apres deploiement : 30-59 => 4-Suspect Dormant uniquement ; >= 60 => 5-Dormant ; < 30 => 1/2/3
WITH ref AS (
    SELECT TRUNC(MAX(LASTPURCHASE_DATE)) AS REF_DATE FROM CMS_RFC.PREPAID_PROFILE_P
),
last_row AS (
    SELECT p.METER, ref.REF_DATE - TRUNC(p.LASTPURCHASE_DATE) AS RECENSE
    FROM CMS_RFC.PREPAID_PROFILE_P p
    CROSS JOIN ref
    WHERE p.VC_DATE = TRUNC(ref.REF_DATE, 'MM')
)
SELECT CASE WHEN r.RECENSE IS NULL THEN 'SANS DATE'
            WHEN r.RECENSE < 30 THEN '0-29'
            WHEN r.RECENSE < 60 THEN '30-59'
            ELSE '60+' END AS RECENCE,
       NVL(t.SEGMENTATION, '(NON CLASSE)') AS SEGMENTATION, COUNT(*) AS CLIENTS
FROM CMS_RFC.TB_CUSTOMERS_LIST t
JOIN last_row r ON r.METER = t.METER_NO
WHERE t.METER = 'PREPAID'
  AND TRIM(t.STATUS) IN ('ACTIVE', 'ACTIVE (PENDING BILLING)', 'SUSPENDED (DELINQUENT ACCOUNT)', 'INACTIVATION IN PROCESS.')
GROUP BY CASE WHEN r.RECENSE IS NULL THEN 'SANS DATE'
              WHEN r.RECENSE < 30 THEN '0-29'
              WHEN r.RECENSE < 60 THEN '30-59'
              ELSE '60+' END,
         NVL(t.SEGMENTATION, '(NON CLASSE)')
ORDER BY 1, 2;

PROMPT == 5. PREPAID sans profil RFM : nouveaux acheteurs / sans achat (via SEGMENT_RFM_2 vide)
SELECT NVL(SEGMENTATION, '(NON CLASSE)') AS SEGMENTATION, COUNT(*) AS CLIENTS
FROM CMS_RFC.TB_CUSTOMERS_LIST
WHERE METER = 'PREPAID'
  AND SEGMENT_RFM_2 IS NULL AND LAST_VC_DATE IS NULL
  AND TRIM(STATUS) IN ('ACTIVE', 'ACTIVE (PENDING BILLING)', 'SUSPENDED (DELINQUENT ACCOUNT)', 'INACTIVATION IN PROCESS.')
GROUP BY SEGMENTATION
ORDER BY 1;

PROMPT == 6. POSTPAID / Compteurs Communicants : doit rester comparable a la reference (regle inchangee)
SELECT METER AS UNIVERS, NVL(SEGMENTATION, '(NON CLASSE)') AS SEGMENTATION, COUNT(*) AS CLIENTS
FROM CMS_RFC.TB_CUSTOMERS_LIST
WHERE METER <> 'PREPAID'
  AND TRIM(STATUS) IN ('ACTIVE', 'ACTIVE (PENDING BILLING)', 'SUSPENDED (DELINQUENT ACCOUNT)', 'INACTIVATION IN PROCESS.')
GROUP BY METER, SEGMENTATION
ORDER BY 1, 2;

PROMPT == 7. Nombre de lignes par univers (tous statuts)
SELECT METER AS UNIVERS, COUNT(*) AS LIGNES FROM CMS_RFC.TB_CUSTOMERS_LIST GROUP BY ROLLUP (METER) ORDER BY 1;

PROMPT == 8. Decomposition du profil Defaillant (colonne 28, apres etape 1 seulement : ORA-00904 avant = normal)
PROMPT    Population = non PREPAID actifs en '6 D...faillant' (libelle amont) ou '8 Autre' (rattache au Defaillant par Extractor)
PROMPT    Reference 13/11 : ALWAYS_LATE 48080 / NEVER_PAID 310096 / SOMETIME_PAID 134600 / total 492776, aucun <NULL>
SELECT NVL(FAILURE_SUBCATEGORY, '<NULL>') AS COMPOSANTE, COUNT(*) AS CLIENTS, COUNT(DISTINCT CONTRACT) AS CONTRATS
FROM CMS_RFC.TB_CUSTOMERS_LIST
WHERE METER <> 'PREPAID'
  AND (SEGMENTATION LIKE '6 D%faillant' OR SEGMENTATION = '8 Autre')
  AND TRIM(STATUS) IN ('ACTIVE', 'ACTIVE (PENDING BILLING)', 'SUSPENDED (DELINQUENT ACCOUNT)', 'INACTIVATION IN PROCESS.')
GROUP BY ROLLUP (NVL(FAILURE_SUBCATEGORY, '<NULL>'))
ORDER BY 1;

PROMPT == 9. Composante hors Defaillant ou hors nomenclature (aucune ligne attendue)
SELECT METER AS UNIVERS, NVL(SEGMENTATION, '(NON CLASSE)') AS SEGMENTATION, FAILURE_SUBCATEGORY AS COMPOSANTE, COUNT(*) AS LIGNES
FROM CMS_RFC.TB_CUSTOMERS_LIST
WHERE FAILURE_SUBCATEGORY IS NOT NULL
  AND (METER = 'PREPAID'
       OR NOT (SEGMENTATION LIKE '6 D%faillant' OR SEGMENTATION = '8 Autre')
       OR SEGMENTATION IS NULL
       OR FAILURE_SUBCATEGORY NOT IN ('ALWAYS_LATE', 'NEVER_PAID', 'SOMETIME_PAID'))
GROUP BY METER, SEGMENTATION, FAILURE_SUBCATEGORY;

EXIT
