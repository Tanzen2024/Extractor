    function mount(win) {
        var doc = win.document;
        var el = null;
        var q = function (sel) { return el.querySelector(sel); };
        var controller;

        function show(node, on) { node.hidden = !on; }

        function render(m) {
            if (!el) return;
            if (!m) {
                el.classList.remove('is-open');
                el.hidden = true;
                return;
            }
            if (!el.firstChild) el.innerHTML = TEMPLATE;
            el.hidden = false;
            // next frame: lets the entry transition run
            win.requestAnimationFrame(function () { el.classList.add('is-open'); });
            el.setAttribute('data-phase', m.phase);

            q('[data-xw-icon]').className = 'bscd-xw__icon ' + (ICONS[m.phase] || ICONS.busy);
            q('[data-xw-title]').textContent = m.title;
            q('[data-xw-state]').textContent = m.state;
            var status = q('[data-xw-status]');
            status.textContent = m.status;
            show(status, !!m.status);

            var progress = q('[data-xw-progress]');
            show(progress, m.percent !== null || m.indeterminate);
            progress.classList.toggle('is-indeterminate', m.percent === null && m.indeterminate);
            var bar = progress.querySelector('.progress-bar');
            if (m.percent !== null) {
                bar.style.width = m.percent + '%';
                bar.setAttribute('aria-valuenow', String(m.percent));
                q('[data-xw-pct]').textContent = m.percent + ' %';
            } else {
                bar.style.width = '';
                bar.removeAttribute('aria-valuenow');
                q('[data-xw-pct]').textContent = '';
            }

            var line = function (sel, text) { var n = q(sel); n.textContent = text; show(n, !!text); return !!text; };
            var stats = [line('[data-xw-counts]', m.counts), line('[data-xw-exported]', m.exported)];
            show(q('[data-xw-stats]'), stats[0] || stats[1]);
            var file = [line('[data-xw-format]', m.format), line('[data-xw-size]', m.size), line('[data-xw-duration]', m.duration)];
            show(q('[data-xw-file]'), file[0] || file[1] || file[2]);
            show(q('[data-xw-download]'), !!m.download);
            q('[data-xw-download-title]').textContent = m.download ? m.download.title : '';
            q('[data-xw-download-text]').textContent = m.download ? m.download.text : '';
            var message = q('[data-xw-message]');
            message.textContent = m.message + (m.reference ? ' (référence : ' + m.reference + ')' : '');
            show(message, !!m.message);
            q('[data-xw-warning]').textContent = m.warning;
            show(q('[data-xw-warning]'), !!m.warning);

            show(q('[data-xw-confirm]'), m.confirming);
            show(q('[data-xw-footer]'), !m.confirming && (m.canCancel || m.canClose || m.cancelling));
            var cancel = q('[data-xw-cancel]');
            show(cancel, m.canCancel || m.cancelling);
            cancel.disabled = m.cancelling;
            var closeBtn = q('[data-xw-close]');
            show(closeBtn, m.canClose);
            closeBtn.textContent = m.closeLabel;
        }

        var deps = {
            fetchJson: function (url, opts) { return win.bscdFetch(url, opts); },
            endpoint: '', // site_url('exports'), read from the markup at boot
            session: storage(function () { return win.sessionStorage; }),
            local: storage(function () { return win.localStorage; }),
            setTimer: function (fn, ms) { return win.setTimeout(fn, ms); },
            clearTimer: function (id) { win.clearTimeout(id); },
            now: function () { return Date.now(); },
            download: function (url) { win.location = url; }, // fallback: Content-Disposition: attachment → the page stays
            downloader: null,
            render: render,
            isHidden: function () { return !!doc.hidden; }
        };

        // Measured download where the browser can stream a response body;
        // otherwise deps.download (window.location) stays the only path.
        var canStream = typeof win.fetch === 'function' && typeof win.ReadableStream === 'function' &&
            !!(win.URL && win.URL.createObjectURL) && 'download' in doc.createElement('a');
        var activeDownloads = 0;
        if (canStream) {
            deps.downloader = createStreamDownloader({
                fetch: function (url, init) { return win.fetch(url, init); },
                save: function (blob, name) {
                    var href = win.URL.createObjectURL(blob);
                    var a = doc.createElement('a');
                    a.href = href;
                    a.download = name;
                    a.style.display = 'none';
                    doc.body.appendChild(a);
                    a.click();
                    a.remove();
                    // Memory cleanup only (the browser has its own reference
                    // once the save has started) — never a completion signal.
                    win.setTimeout(function () { win.URL.revokeObjectURL(href); }, 60000);
                },
                frame: function (fn) { (win.requestAnimationFrame || win.setTimeout)(fn); },
                active: function (delta) { activeDownloads = Math.max(0, activeDownloads + delta); }
            });
            // Leaving the page would abort a download the page itself is
            // receiving: the browser asks for a confirmation first.
            win.addEventListener('beforeunload', function (e) {
                if (activeDownloads === 0) return;
                e.preventDefault();
                e.returnValue = '';
            });
        }
        controller = createExportController(deps);

        function boot() {
            el = doc.getElementById('bscdExportWidget');
            if (!el || !win.bscdFetch) return;
            deps.endpoint = (el.getAttribute('data-endpoint') || '').replace(/\/+$/, '');
            // Buttons only: no outside-click, no Escape — the window is not a modal.
            el.addEventListener('click', function (e) {
                var t = e.target.closest('button');
                if (!t) return;
                if (t.hasAttribute('data-xw-cancel')) controller.cancel();
                else if (t.hasAttribute('data-xw-confirm-yes')) controller.confirmCancel();
                else if (t.hasAttribute('data-xw-keep')) controller.abortCancel();
                else if (t.hasAttribute('data-xw-close')) controller.close();
            });
            controller.resume(); // export started on a previous page of this tab
        }
        if (doc.readyState === 'loading') doc.addEventListener('DOMContentLoaded', boot);
        else boot();

        return {
            begin: controller.begin, attach: controller.attach, syncDone: controller.syncDone,
            fail: controller.fail, empty: controller.empty, isBusy: controller.isBusy
        };
    }

